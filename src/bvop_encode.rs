//! Rectangular progressive **B-VOP encoder** — §7.6.9 mode decision +
//! §6.2.6 emission over the P-VOP encoder's block machinery.
//!
//! Per macroblock the walk evaluates the four §7.6.9 prediction modes
//! against the two bracketing anchors (always the **closed-loop**
//! reconstructions — the decoder-walk outputs of the emitted anchor
//! units):
//!
//! * **direct** (§7.6.9.5) — the per-sub-block `(MVF[i], MVB[i])`
//!   pairs derived from the co-located future-anchor macroblock's
//!   block vectors via the §7.6.9.5.2 TRB/TRD scaling, searched over a
//!   small `MVD` window (the delta is coded with `f_code == 1` and
//!   predictor zero, §7.6.8);
//! * **forward** (§7.6.9.2) / **backward** (§7.6.9.3) — one 16×16 MV
//!   against the past / future anchor (the P encoder's §7.6 motion
//!   search + sub-pel refinement), coded against the §7.6.8 running
//!   per-direction predictor (reset at each row start, updated only by
//!   macroblocks coding that direction);
//! * **interpolated** (§7.6.9.4) — both vectors, averaged prediction.
//!
//! Every candidate's prediction is generated by the decoder's own
//! §7.6.9 machinery ([`BVopMbDecode::reconstruct`] with a zero
//! residual), so the mode decision scores exactly what a conformant
//! decoder will reconstruct. Emission follows the §6.2.6 B-VOP
//! macroblock syntax: `modb` (Table B.3 — `"1"` for a direct zero-delta
//! macroblock with no coded blocks, `"01"` without `cbpb`, `"00"` with),
//! `mb_type` (Table B.4), `cbpb`, `dbquant` (Table 6-33; this encoder
//! keeps a per-VOP quantiser, delta `0`), the `motion_vector()` bodies
//! in §6.2.6 order (forward, backward, direct), and the Table B.17
//! inter `block()` bodies. A macroblock whose co-located future-P
//! macroblock was skipped transmits **no bits at all** (§6.2.6 /
//! §6.3.6 `co_located_not_coded`; §7.6.9.6 reconstructs it as a
//! forward zero-MV copy).
//!
//! The emitted VOP is decoded back through the crate's own
//! [`decode_b_vop_macroblocks`] +
//! [`assemble_b_vop_frame`](crate::frame_decode::assemble_b_vop_frame)
//! walk, closing the loop.
//!
//! This encoder emits **progressive** B-VOPs only, where the
//! §7.7.2.2 interlaced-direct spec-vs-ecosystem divergence (and its
//! transmitted-`MVD == (0, 0)` sub-behaviour, `crate::compat`) cannot
//! arise — a progressive direct macroblock's derivation is identical
//! under both behaviour modes.
//!
//! Provenance: §6.2.5/§6.2.6 syntax, §6.3.6 semantics, §7.6.7–§7.6.9
//! prediction from ISO/IEC 14496-2:2004 (3rd edition), read from
//! `docs/video/mpeg4-visual/ISO_IEC_14496-2-2004-3rd-edition.txt`,
//! via the crate's decoder transcriptions. No third-party source was
//! consulted.

