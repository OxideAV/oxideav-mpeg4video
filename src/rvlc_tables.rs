// RVLC_TCOEF is Table B.23 ("RVLC table for Tcoef") of ISO/IEC
// 14496-2:2004 (3rd edition), read by the agent from
// docs/video/mpeg4-visual/ISO_IEC_14496-2-2004-3rd-edition.txt. Each
// entry is
//   (code_bits, code_len, intra_last, intra_run, intra_level,
//    inter_last, inter_run, inter_level)
// where code_bits / code_len describe the prefix-free reversible VLC
// *without* its trailing sign bit `s`, which is read separately. The
// spec lists the code with the sign appended (column "VLC_CODE", column
// "BITS" counts that sign), so code_len == BITS - 1. The intra and inter
// (LAST, RUN, LEVEL) triples share one code; the table-kind argument
// selects which triple applies. The 169 non-escape EVENTs (INDEX
// 0..=168) are reproduced verbatim; the shared escape EVENT (INDEX 169,
// code "0000s") is handled in texture.rs, not tabulated here. No
// third-party MPEG-4 source was consulted.

