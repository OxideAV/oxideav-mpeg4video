    #[test]
    fn forward_only_half_pel_mv_interpolates() {
        // Half-pel MV = (1, 0) on a horizontal gradient (column i has
        // value 10 + i). The half-pel-x bilinear with rc=0 produces
        // `(A + B + 1) >> 1`. For a 1-pel-spaced gradient A=10+i,
        // B=10+i+1, so `(A+B+1)>>1 = (21+2i)>>1`. For each output
        // column the expected value is `(2*(10+i+origin)+1)>>1` for
        // origin shift 0..15 added to 8 (mb_origin_x).
        let mut fwd = vec![0u8; 64 * 64];
        for y in 0..64 {
            for x in 0..64 {
                fwd[y * 64 + x] = (10 + x).min(255) as u8;
            }
        }
        let bwd = vec![0u8; 64 * 64];
        let fwd_vop = ReferenceVop::new(&fwd, 64, 64).unwrap();
        let bwd_vop = ReferenceVop::new(&bwd, 64, 64).unwrap();
        let mvs = [BVopMvPair {
            forward: MotionVector { x: 1, y: 0 },
            backward: MotionVector { x: 0, y: 0 },
        }; MB_SUB_BLOCKS];

        let out = generate_b_vop_luma_prediction(
            &fwd_vop,
            &bwd_vop,
            &mvs,
            8,
            8,
            0,
            BVopSampleMode::HalfPel,
            BVopPredictionMode::ForwardOnly,
        );

        // mb_origin = (8, 8); half-pel-x integer-pel offset = 0,
        // half_x = true. So at output column i the input is half
        // way between column (8 + i) and (8 + i + 1).
        // Expected: ((10 + 8 + i) + (10 + 8 + i + 1) + 1 - rc) >> 1
        // with rc = vop_rounding_type & 1 = 0
        //        = (37 + 2i) >> 1
        for j in 0..MB_LUMA_SIDE {
            for i in 0..MB_LUMA_SIDE {
                let a = (10 + 8 + i) as u16;
                let b = (10 + 8 + i + 1) as u16;
                let expected = ((a + b + 1) >> 1) as u8;
                assert_eq!(out[j * MB_LUMA_SIDE + i], expected, "(i, j) = ({i}, {j})");
            }
        }
    }

    #[test]
    fn bidirectional_replicates_single_mv_across_all_sub_blocks() {
        // With Bidirectional mode, only mvs[0] is consulted. Plant a
        // sentinel in mvs[1..] and confirm the output ignores them.
        let mut fwd = vec![0u8; 64 * 64];
        let mut bwd = vec![0u8; 64 * 64];
        for (k, (f, b)) in fwd.iter_mut().zip(bwd.iter_mut()).enumerate() {
            *f = (k as u8).wrapping_mul(3);
            *b = (k as u8).wrapping_mul(5).wrapping_add(7);
        }
        let fwd_vop = ReferenceVop::new(&fwd, 64, 64).unwrap();
        let bwd_vop = ReferenceVop::new(&bwd, 64, 64).unwrap();
        let zero = MotionVector { x: 0, y: 0 };
        // Garbage in mvs[1..] — must be ignored.
        let huge = MotionVector { x: 100, y: 100 };
        let mvs = [
            BVopMvPair {
                forward: zero,
                backward: zero,
            },
            BVopMvPair {
                forward: huge,
                backward: huge,
            },
            BVopMvPair {
                forward: huge,
                backward: huge,
            },
            BVopMvPair {
                forward: huge,
                backward: huge,
            },
        ];

        let out = generate_b_vop_luma_prediction(
            &fwd_vop,
            &bwd_vop,
            &mvs,
            8,
            8,
            0,
            BVopSampleMode::HalfPel,
            BVopPredictionMode::Bidirectional,
        );

        // Build the expected 16×16 manually: each pixel is the
        // (fwd + bwd + 1) >> 1 of the integer-pel samples at
        // (8 + i, 8 + j) in both refs.
        for j in 0..MB_LUMA_SIDE {
            for i in 0..MB_LUMA_SIDE {
                let idx = (8 + j) * 64 + (8 + i);
                let f = u16::from(fwd[idx]);
                let b = u16::from(bwd[idx]);
                let expected = ((f + b + 1) >> 1) as u8;
                assert_eq!(out[j * MB_LUMA_SIDE + i], expected, "(i, j) = ({i}, {j})");
            }
        }
    }

