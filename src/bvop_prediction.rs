//! §7.6.9.5.3 generation of prediction blocks for B-VOP macroblocks.
//!
//! Given the resolved forward and backward motion vectors for one B-VOP
//! macroblock — produced by [`crate::motion::direct_mode_motion_vector`]
//! (direct mode) or by [`crate::motion::decode_motion_vector_delta`] +
//! [`crate::motion::reconstruct_motion_vector`] (forward / backward /
//! interpolated mode) — this module fills the per-sub-block 8×8 forward
//! and backward luminance prediction blocks via the §7.6.2.1 (half-pel)
//! or §7.6.2.2 (quarter-pel) interpolation primitives, then averages
//! them pixel-by-pixel using the §7.6.9.4 bidirectional rule
//! `Pi[i][j] = (Pf[i][j] + Pb[i][j] + 1) >> 1` that §7.6.9.5.3 also
//! adopts for direct mode.
//!
//! ## Sub-block layout
//!
//! §7.6.9.5.3 first paragraph: *"Motion compensation for luminance is
//! performed individually on 8x8 blocks to generate a macroblock."*
//! The four 8×8 luminance sub-blocks of one 16×16 macroblock are
//! ordered exactly like Figure 6-8 (the same order [`crate::block`]
//! uses for the intra / inter residual pipeline):
//!
//! ```text
//!     i = 0 (TL)   i = 1 (TR)
//!     i = 2 (BL)   i = 3 (BR)
//! ```
//!
//! For forward-only or backward-only modes (B-VOP `mb_type ∈
//! {forward, backward}`) the single motion vector is replicated across
//! all four sub-block slots — §7.6.9.2 / §7.6.9.3 specify one MV per
//! macroblock for those modes, so the four sub-block predictions are
//! generated by running the same MV against four contiguous origins
//! within the same reference VOP.
//!
//! For direct mode the four sub-block vectors `MVF[i]` / `MVB[i]`
//! generally differ — they come from the four per-sub-block MVs of the
//! co-located anchor MB scaled by §7.6.9.5.2.
//!
//! ## Chrominance prediction
//!
//! The companion entry point
//! [`generate_b_vop_chroma_prediction_into`] (and its
//! [`generate_b_vop_chroma_prediction`] allocator wrapper) produces the
//! 8×8 Cb / Cr B-VOP prediction block per §7.6.9.5.3 second paragraph
//! and §7.6.9.4 — the caller supplies the §7.6.5-reduced forward and
//! backward chroma MVs in half-sample units (from
//! [`crate::chroma_mv::chroma_mv_from_luma_blocks`]) plus a `ReferenceVop`
//! wrapper over each anchor VOP's Cb or Cr plane. §6.1.3.4 places the
//! chroma macroblock origin at half the luma macroblock origin per
//! component (4:2:0). Chroma motion compensation is always half-sample
//! bilinear regardless of the VOL `quarter_sample` flag — §7.6.5 reduces
//! the quarter-pel luma MVs to half-pel chroma MVs before this routine
//! ever sees them, and §7.6.5 paragraph above Table 7-13 spells out
//! *"Half sample values are found using bilinear interpolation as
//! described in subclause 7.6.2"* (i.e. §7.6.2.1, not §7.6.2.2).
//!
//! ## What this module does NOT do
//!
//! * **§7.6.1.6 vector padding.** The caller supplies already-padded
//!   MVs.
//! * **§7.6.5 chroma-MV reduction.** Delegated to
//!   [`crate::chroma_mv::chroma_mv_from_luma_blocks`].
//! * **§7.6.2 interpolation primitives.** Delegated to
//!   [`crate::half_sample::interpolate_block_into`] /
//!   [`crate::quarter_sample::interpolate_block_qpel_into`].
//! * **Residual add and §7.3 step-3 clip.** The output of this module
//!   is the §7.3 step-1 `p[y][x]` prediction; the caller adds the
//!   §7.3 step-2 `f[y][x]` residual and applies the final
//!   `[0, 2^bpp - 1]` clip.
//! * **Reduced-resolution VOP (§7.6.10)** — out of scope.
//! * **Interlaced field-prediction extension** (§7.6.9 last paragraph,
//!   alongside MVF / MVB doubling) — out of scope this round.

use crate::half_sample::{interpolate_block_into, ReferenceVop};
use crate::motion::MotionVector;
use crate::quarter_sample::interpolate_block_qpel_into;

/// Side length, in luminance samples, of one B-VOP MC sub-block.
///
/// §7.6.9.5.3 first paragraph: *"Motion compensation for luminance is
/// performed individually on 8x8 blocks…"*.
pub const SUB_BLOCK_SIDE: usize = 8;

/// Number of 8×8 luminance sub-blocks in one 16×16 macroblock.
///
/// `MB_SUB_BLOCKS = (16 / SUB_BLOCK_SIDE)^2 = 4`. The order is Figure
/// 6-8 (TL → TR → BL → BR).
pub const MB_SUB_BLOCKS: usize = 4;

/// Side length, in luminance samples, of one B-VOP macroblock.
pub const MB_LUMA_SIDE: usize = 16;

/// `MB_LUMA_SIDE * MB_LUMA_SIDE`.
pub const MB_LUMA_PIXELS: usize = MB_LUMA_SIDE * MB_LUMA_SIDE;

/// Sub-pel sample grid the supplied motion vectors are quantised on.
///
/// §6.2.3 / §6.3.3 `quarter_sample`: the VOL-level flag picks between
/// half-pel (legacy) and quarter-pel sub-pel grids. The bitstream's
/// `quarter_sample` value selects the §7.6.2.1 (half-pel bilinear) or
/// §7.6.2.2 (quarter-pel 8-tap FIR + bilinear) interpolation primitive.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BVopSampleMode {
    /// Half-sample units: MV components are 2× the integer-pel offset.
    /// §7.6.2.1 applies.
    HalfPel,
    /// Quarter-sample units: MV components are 4× the integer-pel
    /// offset. §7.6.2.2 applies. `bits_per_pixel` selects the FIR
    /// clip range.
    QuarterPel {
        /// Per-sample bit depth (typically 8). Plumbed into the
        /// quarter-pel FIR's `[0, 2^bpp - 1]` clip; see
        /// [`crate::quarter_sample::interpolate_quarter_pixel`].
        bits_per_pixel: u32,
    },
}

/// Which §7.6.9 mode the caller wants to evaluate.
///
/// `Forward` and `Backward` correspond to the bitstream `mb_type` of
/// the same name (one MV per MB, replicated to all four sub-blocks).
/// `Bidirectional` is `mb_type == interpolated` and supplies two MVs
/// — also one-per-MB, replicated.
///
/// `Direct` is the §7.6.9.5 direct mode and supplies one `MVF[i]` /
/// `MVB[i]` pair per sub-block (four pairs total). The caller derives
/// the pairs via [`crate::motion::direct_mode_motion_vector`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BVopPredictionMode {
    /// `mb_type == forward`. Use only `forward[0]`; replicate across
    /// the four sub-blocks.
    ForwardOnly,
    /// `mb_type == backward`. Use only `backward[0]`; replicate across
    /// the four sub-blocks.
    BackwardOnly,
    /// `mb_type == interpolated`. Use `forward[0]` (replicated) and
    /// `backward[0]` (replicated), then §7.6.9.4 average.
    Bidirectional,
    /// `mb_type == direct`. Use the four `forward[i]` and the four
    /// `backward[i]` per-sub-block vectors, then §7.6.9.5.3 average.
    Direct,
}

/// Per-sub-block motion-vector triple consumed by
/// [`generate_b_vop_luma_prediction_into`].
///
/// Index `i` follows the Figure 6-8 sub-block order
/// (TL=0, TR=1, BL=2, BR=3).
///
/// For `ForwardOnly` / `BackwardOnly` / `Bidirectional` the caller can
/// pass `[mv; 4]` — only `[0]` is read.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BVopMvPair {
    /// Forward motion vector for sub-block `i`. Units match the
    /// [`BVopSampleMode`] passed alongside.
    pub forward: MotionVector,
    /// Backward motion vector for sub-block `i`. Units match the
    /// [`BVopSampleMode`] passed alongside.
    pub backward: MotionVector,
}

/// §7.6.9.4 bidirectional averaging.
///
/// Implements `out[k] = (a[k] + b[k] + 1) >> 1` for every index. This
/// is the same rule §7.6.9.5.3 re-uses for direct-mode averaging, and
/// the same rule §7.6.9.4 specifies for `mb_type == interpolated`.
///
/// `a` and `b` and `out` must have the same length. Arithmetic is in
/// `u16` so the `+ 1` step cannot overflow even for `u8 == 255` in
/// both operands.
///
/// # Panics
///
/// Panics if `a.len() != b.len()` or `out.len() < a.len()`.
///
/// ```
/// use oxideav_mpeg4video::bvop_prediction::average_bidirectional_into;
/// let a = [0u8, 100, 255, 1];
/// let b = [0u8, 102, 255, 2];
/// let mut out = [0u8; 4];
/// average_bidirectional_into(&a, &b, &mut out);
/// // (0+0+1)>>1=0, (100+102+1)>>1=101, (255+255+1)>>1=255, (1+2+1)>>1=2
/// assert_eq!(out, [0, 101, 255, 2]);
/// ```
pub fn average_bidirectional_into(a: &[u8], b: &[u8], out: &mut [u8]) {
    assert!(
        a.len() == b.len(),
        "average_bidirectional_into: a.len() ({}) != b.len() ({})",
        a.len(),
        b.len(),
    );
    assert!(
        out.len() >= a.len(),
        "average_bidirectional_into: out.len() ({}) < a.len() ({})",
        out.len(),
        a.len(),
    );
    for (k, slot) in out.iter_mut().enumerate().take(a.len()) {
        // u16 keeps `255 + 255 + 1 = 511` well within range.
        let sum = u16::from(a[k]) + u16::from(b[k]) + 1;
        *slot = (sum >> 1) as u8;
    }
}

/// Convenience wrapper around [`average_bidirectional_into`] that
/// returns a freshly allocated `Vec<u8>`.
pub fn average_bidirectional(a: &[u8], b: &[u8]) -> Vec<u8> {
    let mut out = vec![0u8; a.len()];
    average_bidirectional_into(a, b, &mut out);
    out
}

/// Interpolate one 8×8 sub-block at the requested origin using
/// `forward` or `backward` reference VOP depending on the supplied MV
/// and reference plane.
//
// Inputs map one-for-one to the §7.6.2 interpolation primitives —
// a struct wrapper would obscure the call site.
#[allow(clippy::too_many_arguments)]
fn interpolate_sub_block(
    reference: &ReferenceVop<'_>,
    mv: MotionVector,
    origin_x: i32,
    origin_y: i32,
    mode: BVopSampleMode,
    vop_rounding_type: u8,
    out: &mut [u8],
) {
    match mode {
        BVopSampleMode::HalfPel => {
            interpolate_block_into(
                reference,
                mv.x,
                mv.y,
                origin_x,
                origin_y,
                SUB_BLOCK_SIDE,
                SUB_BLOCK_SIDE,
                vop_rounding_type,
                out,
            );
        }
        BVopSampleMode::QuarterPel { bits_per_pixel } => {
            interpolate_block_qpel_into(
                reference,
                mv.x,
                mv.y,
                origin_x,
                origin_y,
                SUB_BLOCK_SIDE,
                SUB_BLOCK_SIDE,
                vop_rounding_type,
                bits_per_pixel,
                out,
            );
        }
    }
}

/// Sub-block top-left origin offsets within a 16×16 macroblock in the
/// Figure 6-8 order (TL, TR, BL, BR).
///
/// Returned as `(dx, dy)` pairs in luminance samples, with the
/// macroblock's own top-left at `(0, 0)`. Adding the macroblock origin
/// gives the absolute sub-block origin for the §7.6.2 fetch.
pub const SUB_BLOCK_OFFSETS: [(i32, i32); MB_SUB_BLOCKS] = [
    (0, 0),                                         // i = 0 — top-left
    (SUB_BLOCK_SIDE as i32, 0),                     // i = 1 — top-right
    (0, SUB_BLOCK_SIDE as i32),                     // i = 2 — bottom-left
    (SUB_BLOCK_SIDE as i32, SUB_BLOCK_SIDE as i32), // i = 3 — bottom-right
];

/// Copy an 8×8 sub-block laid out row-major (length 64) into the
/// `MB_LUMA_SIDE × MB_LUMA_SIDE` macroblock buffer at sub-block index
/// `sub_block_index`.
fn place_sub_block(sub: &[u8], sub_block_index: usize, mb_buf: &mut [u8]) {
    let (dx, dy) = SUB_BLOCK_OFFSETS[sub_block_index];
    let dx = dx as usize;
    let dy = dy as usize;
    for j in 0..SUB_BLOCK_SIDE {
        let src_row = &sub[j * SUB_BLOCK_SIDE..(j + 1) * SUB_BLOCK_SIDE];
        let dst_row_start = (dy + j) * MB_LUMA_SIDE + dx;
        mb_buf[dst_row_start..dst_row_start + SUB_BLOCK_SIDE].copy_from_slice(src_row);
    }
}

/// Generate the §7.6.9.5.3 16×16 luminance B-VOP prediction macroblock
/// into a caller-supplied 256-byte buffer.
///
/// Writes per-sub-block 8×8 prediction blocks at the Figure 6-8
/// positions, applying §7.6.9.4 / §7.6.9.5.3's
/// `Pi[i][j] = (Pf[i][j] + Pb[i][j] + 1) >> 1` averaging for
/// `Bidirectional` / `Direct` modes; in `ForwardOnly` / `BackwardOnly`
/// modes the chosen single-side prediction is written directly without
/// averaging.
///
/// `mvs[i]` carries the per-sub-block forward and backward MV. For
/// `ForwardOnly` / `BackwardOnly` / `Bidirectional` only `mvs[0]` is
/// consulted (and replicated to all four sub-blocks). For `Direct`
/// each sub-block uses its own pair.
///
/// `forward_ref` is the §7.6.9.5.1-padded previous anchor VOP's luma
/// plane; `backward_ref` is the temporally next anchor VOP's luma
/// plane (the `*_ref` arguments are consulted only when the mode
/// actually needs them).
///
/// `mb_origin_x` / `mb_origin_y` are the macroblock's top-left
/// integer-pel position within the *current* (predicted) B-VOP, in
/// luminance samples (e.g. macroblock column `c`, row `r` maps to
/// `(16*c, 16*r)`).
///
/// `vop_rounding_type ∈ {0, 1}` is the VOP-header field. For B-VOPs
/// §6.3.5 / §7.6.2 fix `vop_rounding_type = 0` per the B-VOP
/// constraint; the field is plumbed through unchanged in case the
/// caller wishes to enforce it differently.
///
/// `mode` selects half-pel or quarter-pel interpolation, matching the
/// VOL-level `quarter_sample` flag.
///
/// `prediction_mode` selects one of the four §7.6.9 modes (forward,
/// backward, bidirectional, direct).
///
/// `out` must hold at least [`MB_LUMA_PIXELS`] samples; the macroblock
/// is laid out row-major as `out[j * MB_LUMA_SIDE + i]`.
///
/// # Panics
///
/// Panics if `out.len() < MB_LUMA_PIXELS`.
//
// Args map directly to the §7.6.9.5.3 inputs. Grouping them into a
// config struct would force the caller into a builder pattern for a
// one-shot per-macroblock call.
#[allow(clippy::too_many_arguments)]
pub fn generate_b_vop_luma_prediction_into(
    forward_ref: &ReferenceVop<'_>,
    backward_ref: &ReferenceVop<'_>,
    mvs: &[BVopMvPair; MB_SUB_BLOCKS],
    mb_origin_x: i32,
    mb_origin_y: i32,
    vop_rounding_type: u8,
    mode: BVopSampleMode,
    prediction_mode: BVopPredictionMode,
    out: &mut [u8],
) {
    assert!(
        out.len() >= MB_LUMA_PIXELS,
        "generate_b_vop_luma_prediction_into: out.len() ({}) < {}",
        out.len(),
        MB_LUMA_PIXELS,
    );

    match prediction_mode {
        // §7.6.9.2 / §7.6.9.3 / §7.6.9.4: forward, backward, and
        // interpolated modes carry one MV per direction for the whole
        // macroblock and compensate it as a single 16×16 block. The
        // distinction matters in quarter-sample mode: the §7.6.2.2
        // block-boundary mirroring is applied at the edges of the MC
        // block, so a 16×16 fetch is *not* equivalent to four 8×8
        // fetches with the same vector (the §7.6.9.5.3 NOTE spells
        // this out for the direct-mode side of the contrast).
        BVopPredictionMode::ForwardOnly => {
            interpolate_mb_block(
                forward_ref,
                mvs[0].forward,
                mb_origin_x,
                mb_origin_y,
                mode,
                vop_rounding_type,
                &mut out[..MB_LUMA_PIXELS],
            );
        }
        BVopPredictionMode::BackwardOnly => {
            interpolate_mb_block(
                backward_ref,
                mvs[0].backward,
                mb_origin_x,
                mb_origin_y,
                mode,
                vop_rounding_type,
                &mut out[..MB_LUMA_PIXELS],
            );
        }
        BVopPredictionMode::Bidirectional => {
            let mut buf_f = [0u8; MB_LUMA_PIXELS];
            let mut buf_b = [0u8; MB_LUMA_PIXELS];
            interpolate_mb_block(
                forward_ref,
                mvs[0].forward,
                mb_origin_x,
                mb_origin_y,
                mode,
                vop_rounding_type,
                &mut buf_f,
            );
            interpolate_mb_block(
                backward_ref,
                mvs[0].backward,
                mb_origin_x,
                mb_origin_y,
                mode,
                vop_rounding_type,
                &mut buf_b,
            );
            average_bidirectional_into(&buf_f, &buf_b, &mut out[..MB_LUMA_PIXELS]);
        }
        // §7.6.9.5.3: direct mode compensates the four 8×8 luminance
        // blocks individually, each with its own (MVF[i], MVB[i]) pair
        // — and, in quarter-sample mode, with the §7.6.2.2 mirroring at
        // each 8×8 block boundary.
        BVopPredictionMode::Direct => {
            let mut sub_buf_f = [0u8; SUB_BLOCK_SIDE * SUB_BLOCK_SIDE];
            let mut sub_buf_b = [0u8; SUB_BLOCK_SIDE * SUB_BLOCK_SIDE];
            let mut sub_buf_avg = [0u8; SUB_BLOCK_SIDE * SUB_BLOCK_SIDE];
            for (i, &(dx, dy)) in SUB_BLOCK_OFFSETS.iter().enumerate() {
                let origin_x = mb_origin_x + dx;
                let origin_y = mb_origin_y + dy;
                let pair = mvs[i];
                interpolate_sub_block(
                    forward_ref,
                    pair.forward,
                    origin_x,
                    origin_y,
                    mode,
                    vop_rounding_type,
                    &mut sub_buf_f,
                );
                interpolate_sub_block(
                    backward_ref,
                    pair.backward,
                    origin_x,
                    origin_y,
                    mode,
                    vop_rounding_type,
                    &mut sub_buf_b,
                );
                average_bidirectional_into(&sub_buf_f, &sub_buf_b, &mut sub_buf_avg);
                place_sub_block(&sub_buf_avg, i, out);
            }
        }
    }
}

/// Interpolate one full 16×16 macroblock at the requested origin —
/// the single-MC-block form used by the §7.6.9.2 / §7.6.9.3 / §7.6.9.4
/// (forward / backward / interpolated) B-VOP modes.
//
// Inputs map one-for-one to the §7.6.2 interpolation primitives —
// a struct wrapper would obscure the call site.
#[allow(clippy::too_many_arguments)]
fn interpolate_mb_block(
    reference: &ReferenceVop<'_>,
    mv: MotionVector,
    origin_x: i32,
    origin_y: i32,
    mode: BVopSampleMode,
    vop_rounding_type: u8,
    out: &mut [u8],
) {
    match mode {
        BVopSampleMode::HalfPel => {
            interpolate_block_into(
                reference,
                mv.x,
                mv.y,
                origin_x,
                origin_y,
                MB_LUMA_SIDE,
                MB_LUMA_SIDE,
                vop_rounding_type,
                out,
            );
        }
        BVopSampleMode::QuarterPel { bits_per_pixel } => {
            interpolate_block_qpel_into(
                reference,
                mv.x,
                mv.y,
                origin_x,
                origin_y,
                MB_LUMA_SIDE,
                MB_LUMA_SIDE,
                vop_rounding_type,
                bits_per_pixel,
                out,
            );
        }
    }
}

/// Convenience wrapper around [`generate_b_vop_luma_prediction_into`]
/// that returns a freshly allocated `Vec<u8>` of length
/// [`MB_LUMA_PIXELS`].
#[allow(clippy::too_many_arguments)]
pub fn generate_b_vop_luma_prediction(
    forward_ref: &ReferenceVop<'_>,
    backward_ref: &ReferenceVop<'_>,
    mvs: &[BVopMvPair; MB_SUB_BLOCKS],
    mb_origin_x: i32,
    mb_origin_y: i32,
    vop_rounding_type: u8,
    mode: BVopSampleMode,
    prediction_mode: BVopPredictionMode,
) -> Vec<u8> {
    let mut out = vec![0u8; MB_LUMA_PIXELS];
    generate_b_vop_luma_prediction_into(
        forward_ref,
        backward_ref,
        mvs,
        mb_origin_x,
        mb_origin_y,
        vop_rounding_type,
        mode,
        prediction_mode,
        &mut out,
    );
    out
}

/// Side length, in chrominance samples, of one B-VOP chroma prediction
/// block (Cb or Cr) for a 4:2:0 macroblock.
///
/// §6.1.3.4: each 16×16 luma macroblock pairs with one 8×8 Cb block and
/// one 8×8 Cr block in 4:2:0. §7.6.9.5.3 second paragraph treats the
/// chrominance prediction as a single MC block (no per-sub-block split
/// — the §7.6.5 reduction folds the K luma MVs into a single chroma MV
/// per direction).
pub const CHROMA_BLOCK_SIDE: usize = 8;

/// `CHROMA_BLOCK_SIDE * CHROMA_BLOCK_SIDE`.
pub const CHROMA_BLOCK_PIXELS: usize = CHROMA_BLOCK_SIDE * CHROMA_BLOCK_SIDE;

/// Generate the §7.6.9.5.3 / §7.6.9.4 8×8 chrominance B-VOP prediction
/// block (Cb or Cr) into a caller-supplied 64-sample buffer.
///
/// Chroma motion compensation in MPEG-4 Part 2 §7.6.9.5.3 follows two
/// steps:
///
/// 1. **§7.6.5 reduction.** The K forward luma MVs `MVF[i]` are
///    reduced to a single forward chroma MV via
///    [`crate::chroma_mv::chroma_mv_from_luma_blocks`] (quarter-pel
///    luma callers pre-apply
///    [`crate::quarter_sample::reduce_qpel_to_half_pel_chroma`] per
///    component first). The backward side is reduced the same way.
///    The caller does this BEFORE calling this routine.
///
/// 2. **§7.6.2.1 bilinear interpolation + §7.6.9.4 averaging.** Each
///    8×8 chroma block is filled by half-sample bilinear interpolation
///    against the reduced chroma MV in the matching anchor VOP's
///    chroma plane. `Bidirectional` and `Direct` modes average the
///    forward and backward predictions pixel-by-pixel via
///    `(Pf + Pb + 1) >> 1` (the same rule §7.6.9.4 specifies for
///    `mb_type == interpolated` — §7.6.9.5.3 last paragraph says
///    *"The rest process is the same as the chrominance motion
///    compensation of the bi-directional mode described in
///    subclause 7.6.9.4"*).
///
/// # Arguments
///
/// * `forward_chroma_ref` — §7.6.9.5.1-padded previous anchor VOP's
///   chroma plane (Cb for the Cb call, Cr for the Cr call).
///   `ReferenceVop::new(plane, chroma_w, chroma_h)` where
///   `chroma_w = luma_w / 2` and `chroma_h = luma_h / 2` per §6.1.3.4
///   4:2:0 sub-sampling. Consulted only when the mode actually needs
///   the forward side (`ForwardOnly`, `Bidirectional`, `Direct`).
/// * `backward_chroma_ref` — same for the temporally next anchor VOP.
///   Consulted only when the mode needs the backward side
///   (`BackwardOnly`, `Bidirectional`, `Direct`).
/// * `forward_chroma_mv` / `backward_chroma_mv` — the §7.6.5-reduced
///   chroma MVs in **half-sample units**. `Direct` and `Bidirectional`
///   modes use both; `ForwardOnly` consults only forward; `BackwardOnly`
///   consults only backward.
/// * `chroma_mb_origin_x` / `chroma_mb_origin_y` — the chrominance
///   macroblock's top-left integer-pel position within the *current*
///   (predicted) B-VOP, in chrominance samples. §6.1.3.4 places the
///   chroma origin at half the luma origin: macroblock column `c`,
///   row `r` maps to `(8*c, 8*r)` in chroma units.
/// * `vop_rounding_type ∈ {0, 1}` — the VOP-header field. For B-VOPs
///   §6.3.5 / §7.6.2 fix `vop_rounding_type = 0`; the value is plumbed
///   through unchanged so the caller can enforce that constraint
///   independently.
/// * `prediction_mode` — one of the four §7.6.9 modes. For B-VOPs
///   §7.6.9.5.3 second paragraph treats forward / backward / bi-
///   directional / direct identically for chroma except for which
///   side(s) of the prediction equation are evaluated.
/// * `out` — buffer of length ≥ [`CHROMA_BLOCK_PIXELS`] (64). Filled
///   row-major as `out[j * CHROMA_BLOCK_SIDE + i]`.
///
/// Each chroma plane (Cb and Cr) is called separately with its own
/// `forward_chroma_ref` / `backward_chroma_ref`. The reduced chroma MV
/// is the same for Cb and Cr — the per-plane separation is only the
/// reference data.
///
/// # Panics
///
/// Panics if `out.len() < CHROMA_BLOCK_PIXELS`.
//
// Inputs map one-for-one to the §7.6.9.5.3 / §7.6.9.4 chroma MC
// equations — the four reference / MV slots, the two chroma origin
// scalars, the rounding bit, the mode selector, and the output buffer.
// Bundling into a struct would force a builder pattern around a
// one-shot per-macroblock call.
#[allow(clippy::too_many_arguments)]
pub fn generate_b_vop_chroma_prediction_into(
    forward_chroma_ref: &ReferenceVop<'_>,
    backward_chroma_ref: &ReferenceVop<'_>,
    forward_chroma_mv: MotionVector,
    backward_chroma_mv: MotionVector,
    chroma_mb_origin_x: i32,
    chroma_mb_origin_y: i32,
    vop_rounding_type: u8,
    prediction_mode: BVopPredictionMode,
    out: &mut [u8],
) {
    assert!(
        out.len() >= CHROMA_BLOCK_PIXELS,
        "generate_b_vop_chroma_prediction_into: out.len() ({}) < {}",
        out.len(),
        CHROMA_BLOCK_PIXELS,
    );

    // Reusable scratch buffers for the per-side interpolation. Held in
    // local arrays so the function stays allocation-free in the steady
    // state — the caller-supplied `out` is filled at the end.
    let mut buf_f = [0u8; CHROMA_BLOCK_PIXELS];
    let mut buf_b = [0u8; CHROMA_BLOCK_PIXELS];

    match prediction_mode {
        BVopPredictionMode::ForwardOnly => {
            interpolate_block_into(
                forward_chroma_ref,
                forward_chroma_mv.x,
                forward_chroma_mv.y,
                chroma_mb_origin_x,
                chroma_mb_origin_y,
                CHROMA_BLOCK_SIDE,
                CHROMA_BLOCK_SIDE,
                vop_rounding_type,
                &mut out[..CHROMA_BLOCK_PIXELS],
            );
        }
        BVopPredictionMode::BackwardOnly => {
            interpolate_block_into(
                backward_chroma_ref,
                backward_chroma_mv.x,
                backward_chroma_mv.y,
                chroma_mb_origin_x,
                chroma_mb_origin_y,
                CHROMA_BLOCK_SIDE,
                CHROMA_BLOCK_SIDE,
                vop_rounding_type,
                &mut out[..CHROMA_BLOCK_PIXELS],
            );
        }
        BVopPredictionMode::Bidirectional | BVopPredictionMode::Direct => {
            interpolate_block_into(
                forward_chroma_ref,
                forward_chroma_mv.x,
                forward_chroma_mv.y,
                chroma_mb_origin_x,
                chroma_mb_origin_y,
                CHROMA_BLOCK_SIDE,
                CHROMA_BLOCK_SIDE,
                vop_rounding_type,
                &mut buf_f,
            );
            interpolate_block_into(
                backward_chroma_ref,
                backward_chroma_mv.x,
                backward_chroma_mv.y,
                chroma_mb_origin_x,
                chroma_mb_origin_y,
                CHROMA_BLOCK_SIDE,
                CHROMA_BLOCK_SIDE,
                vop_rounding_type,
                &mut buf_b,
            );
            average_bidirectional_into(&buf_f, &buf_b, &mut out[..CHROMA_BLOCK_PIXELS]);
        }
    }
}

