    #[test]
    fn average_bidirectional_zero_zero_is_zero() {
        // (0 + 0 + 1) >> 1 = 0
        let out = average_bidirectional(&[0u8; 4], &[0u8; 4]);
        assert_eq!(out, vec![0u8; 4]);
    }

    #[test]
    fn average_bidirectional_two_equal_values_returns_them() {
        // Equal values: (x + x + 1) >> 1 = x  for any x in 0..=255.
        // The +1 plus the shift effectively rounds up.
        for x in (0u8..=255).step_by(17) {
            let out = average_bidirectional(&[x], &[x]);
            assert_eq!(out, vec![x], "x = {x}");
        }
    }

    #[test]
    fn average_bidirectional_rounds_up_on_ties() {
        // §7.6.9.4 averaging rounds up on the half-tie because of the
        // `+ 1` in the formula. (100 + 101 + 1) >> 1 = 202 >> 1 = 101.
        let out = average_bidirectional(&[100], &[101]);
        assert_eq!(out, vec![101]);
        // (101 + 100 + 1) >> 1 = same as above by commutativity.
        let out2 = average_bidirectional(&[101], &[100]);
        assert_eq!(out2, vec![101]);
    }

    #[test]
    fn average_bidirectional_saturates_at_max() {
        // (255 + 255 + 1) >> 1 = 511 >> 1 = 255. No overflow.
        let out = average_bidirectional(&[255u8; 8], &[255u8; 8]);
        assert_eq!(out, vec![255u8; 8]);
    }

    #[test]
    fn average_bidirectional_8x8_block_matches_pixel_by_pixel() {
        // Build two 8×8 blocks with deterministic gradients and verify
        // the row-major output matches the spec's (Pf + Pb + 1) >> 1
        // pixel-by-pixel.
        let mut pf = [0u8; 64];
        let mut pb = [0u8; 64];
        for k in 0..64u32 {
            pf[k as usize] = (k * 3 % 256) as u8;
            pb[k as usize] = (k * 5 + 7) as u8;
        }
        let out = average_bidirectional(&pf, &pb);
        for k in 0..64 {
            let expected = ((u16::from(pf[k]) + u16::from(pb[k]) + 1) >> 1) as u8;
            assert_eq!(out[k], expected, "k = {k}");
        }
    }

