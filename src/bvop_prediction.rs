        // prediction must be all 80s (no interpolation; no averaging
        // with the backward side).
        let fwd = flat_ref(80);
        let bwd = flat_ref(200); // Should never be sampled.
        let fwd_vop = ReferenceVop::new(&fwd, 64, 64).unwrap();
        let bwd_vop = ReferenceVop::new(&bwd, 64, 64).unwrap();
