    #[test]
    fn direct_mode_per_sub_block_mvs_select_distinct_origins() {
        // Direct mode pulls distinct MVs per sub-block. Forge a
        // reference where each sub-block "origin + MV" lands on a
        // distinct flat region and confirm the per-sub-block fetches
        // honour their per-i MV (i.e. the dispatch keys on `i`, not
        // on `0` as it does for ForwardOnly / BackwardOnly /
        // Bidirectional).
        //
        // Macroblock origin is (8, 8). Sub-block i origins (without
        // MV) are (8, 8), (16, 8), (8, 16), (16, 16). MVF[i] shifts
        // sub-block i onto its own flat patch in the forward
        // reference; we set MVB[i] = MVF[i] and use the SAME plane as
        // the backward reference so the §7.6.9.5.3 averaging is the
        // identity and we can verify the per-sub-block fetch routed
        // correctly without weaving averaging into the assertion.

        let mut fwd = vec![0u8; 96 * 96];
        // Plant four distinct flat 8×8 patches at known positions in
        // the forward reference. The four entries below correspond to
        // the four `SUB_BLOCK_OFFSETS` slots (TL, TR, BL, BR), so each
        // entry's `(px, py)` is the position the matching sub-block
        // should pull from after applying its MV. TR sits to the right
        // of TL (x increases), BL sits below TL (y increases), BR is
        // diagonally opposite (x and y both increase).
        let patches = [
            (40, 40, 100u8), // sub-block 0 — TL target
            (56, 40, 110),   // sub-block 1 — TR target (x increases)
            (40, 56, 120),   // sub-block 2 — BL target (y increases)
            (56, 56, 130),   // sub-block 3 — BR target
        ];
        for (px, py, val) in patches {
            for j in 0..8 {
                for i in 0..8 {
                    fwd[(py + j) * 96 + (px + i)] = val;
                }
            }
        }
        let fwd_vop = ReferenceVop::new(&fwd, 96, 96).unwrap();
        // Use the same plane as the backward reference and set MVB =
        // MVF below; (x + x + 1) >> 1 = x for any x, so averaging is
        // the identity for this test.
        let bwd_vop = ReferenceVop::new(&fwd, 96, 96).unwrap();

        // Macroblock origin is (8, 8). For sub-block i to fetch from
        // patch i (origin (px, py)) at half-pel-x = 0, half-pel-y =
        // 0, we need integer MV = (px - origin_x, py - origin_y),
        // and half-pel-encoded that's 2× the integer.
        let mb_origin_x = 8i32;
        let mb_origin_y = 8i32;
        let mut mvs = [BVopMvPair {
            forward: MotionVector { x: 0, y: 0 },
            backward: MotionVector { x: 0, y: 0 },
        }; MB_SUB_BLOCKS];
        for (i, (px, py, _)) in patches.iter().enumerate() {
            let (dx, dy) = SUB_BLOCK_OFFSETS[i];
            let target_x = *px as i32;
            let target_y = *py as i32;
            let sub_origin_x = mb_origin_x + dx;
            let sub_origin_y = mb_origin_y + dy;
            let mv_x_int = target_x - sub_origin_x;
            let mv_y_int = target_y - sub_origin_y;
            let mv = MotionVector {
                x: mv_x_int * 2,
                y: mv_y_int * 2,
            };
            mvs[i].forward = mv;
            mvs[i].backward = mv;
        }

        let out = generate_b_vop_luma_prediction(
            &fwd_vop,
            &bwd_vop,
            &mvs,
            mb_origin_x,
            mb_origin_y,
            0,
            BVopSampleMode::HalfPel,
            BVopPredictionMode::Direct,
        );

        // Each sub-block of `out` must equal its target patch value.
        for (i, (_, _, val)) in patches.iter().enumerate() {
            let (dx, dy) = SUB_BLOCK_OFFSETS[i];
            for sj in 0..SUB_BLOCK_SIDE {
                for si in 0..SUB_BLOCK_SIDE {
                    let out_x = dx as usize + si;
                    let out_y = dy as usize + sj;
                    let got = out[out_y * MB_LUMA_SIDE + out_x];
                    assert_eq!(
                        got, *val,
                        "sub_block {i} pixel ({si}, {sj}) expected {val}, got {got}"
                    );
                }
            }
        }
    }

